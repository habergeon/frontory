async (page, baseUrl = 'http://127.0.0.1:4187') => {
  const checks = [], measurements = []
  const check = (name, ok) => { checks.push({ name, ok }); if (!ok) throw Error(name) }
  const read = () => page.locator('.current-lesson-actions button').first().click()
  const ready = () => page.locator('.document-reader article[aria-busy="false"] h1').waitFor()
  const identical = () => page.evaluate(() => {
    const before = window.l03
    return before.editor.getModel() === before.model && before.model.getVersionId() === before.version && JSON.stringify(before.editor.getSelection()) === before.selection && document.querySelector('.workspace iframe') === before.frame && before.frame.srcdoc === before.srcdoc && before.frame.contentWindow === before.frameWindow && before.loads === 0 && document.querySelector('.notes-editor') === before.notes && before.notes.value === before.notesValue && JSON.stringify({ ...localStorage }) === before.storage
  })
  for (const locale of ['ko', 'en']) for (const width of [390, 768, 1024, 1100, 1440]) {
    const label = locale + ' ' + width
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    await page.goto(baseUrl + (locale === 'en' ? '/en/' : '/') + '?reader=1#javascript-step-02', { waitUntil: 'domcontentloaded' })
    await page.waitForFunction(() => document.readyState === 'complete')
    await page.waitForSelector('.workspace iframe', { state: 'attached' })
    await page.locator('#tab-notes').evaluate(button => button.click())
    await page.locator('.notes-editor').fill(`# L03 preserved notes

읽던 문서와 함께 남긴 필기입니다.`)
    await page.waitForFunction(() => JSON.stringify({ ...localStorage }).includes('L03 preserved notes'))
    await page.evaluate(async () => {
      const { monaco } = await import('/src/editor/monaco.ts')
      const editor = monaco.editor.getEditors()[0], model = editor.getModel()
      editor.pushUndoStop()
      const original = model.getValue()
      editor.executeEdits('l03-proof', [{ range: new monaco.Range(1, 1, 1, 1), text: '// L03 preserved edit\n' }])
      editor.pushUndoStop()
      editor.setSelection(new monaco.Range(2, 1, 2, 4))
      window.l03 = { editor, model, original }
    })
    await page.waitForFunction(() => JSON.stringify({ ...localStorage }).includes('L03 preserved edit'))
    await page.waitForFunction(() => /실행 중|Running/.test(document.querySelector('.preview-status')?.textContent ?? ''))
    await page.evaluate(() => Object.assign(window.l03, { version: window.l03.model.getVersionId(), selection: JSON.stringify(window.l03.editor.getSelection()), frame: document.querySelector('.workspace iframe'), notes: document.querySelector('.notes-editor'), storage: JSON.stringify({ ...localStorage }), srcdoc: document.querySelector('.workspace iframe').srcdoc, frameWindow: document.querySelector('.workspace iframe').contentWindow, loads: 0, notesValue: document.querySelector('.notes-editor').value }))
    await page.evaluate(() => window.l03.frame.addEventListener('load', () => { window.l03.loads += 1 }))
    await read()
    await ready()
    const originalTitle = await page.locator('.document-reader article h1').first().textContent()
    const geometry = await page.locator('.document-reader').evaluate(reader => {
      const header = document.querySelector('.learning-header').getBoundingClientRect(), title = reader.querySelector('.dialog-header').getBoundingClientRect(), close = reader.querySelector('.dialog-header button').getBoundingClientRect()
      return { readerScrollMarginTop: getComputedStyle(reader).scrollMarginTop, headerHeight: header.height, headerBottom: header.bottom, navigationBottom: Math.max(header.bottom, document.querySelector('.reader-view-controls').getBoundingClientRect().bottom), readerWidth: reader.getBoundingClientRect().width, titleTop: title.top, closeTop: close.top, closeBottom: close.bottom, viewport: innerWidth, documentWidth: document.documentElement.scrollWidth, codeWidth: document.querySelector('#panel-code').getBoundingClientRect().width }
    })
    measurements.push({ label, ...geometry })
    check(label + ' title and close clear sticky header', geometry.titleTop >= geometry.navigationBottom && geometry.titleTop <= geometry.navigationBottom + 32 && geometry.closeTop >= geometry.navigationBottom && geometry.closeBottom <= (width === 390 ? 844 : 1000))
    if (width <= 1099) check(label + ' mobile view controls remain visible', await page.locator('.reader-view-controls').evaluate(controls => { const bounds = controls.getBoundingClientRect(); return bounds.top >= document.querySelector('.learning-header').getBoundingClientRect().bottom && bounds.bottom <= innerHeight }))
    check(label + ' no horizontal overflow', geometry.documentWidth <= width)
    check(label + ' reader is nonmodal and focused', await page.locator('.document-reader').evaluate(reader => document.activeElement === reader && !document.querySelector('dialog:modal')))
    check(label + ' opening preserves workspace state', await identical())
    await page.locator('.document-reader .document-nav button').nth(1).click()
    await ready()
    check(label + ' roadmap navigation changes document', await page.locator('.document-reader article h1').first().textContent() !== originalTitle)
    await read()
    await ready()
    check(label + ' same unit CTA returns from roadmap', await page.locator('.document-reader article h1').first().textContent() === originalTitle)
    if (width <= 1099) {
      await page.locator('.reader-view-controls button').last().click()
      await page.locator('#tab-notes').click()
      await page.locator('.reader-view-controls button').first().click()
      await page.locator('.reader-view-controls button').last().click()
      check(label + ' mobile practice restores selected notes panel', await page.locator('#panel-notes').isVisible() && !await page.locator('.document-reader').isVisible())
      await page.locator('.reader-view-controls button').first().click()
    } else {
      check(label + ' desktop code and notes remain accessible', await page.locator('#panel-code').isVisible() && await page.locator('#panel-notes').isVisible())
      await page.locator('.notes-editor').focus()
      await page.keyboard.press('Escape')
      check(label + ' Escape in practice leaves reader open', await page.locator('.document-reader').count() === 1)
    }
    await page.locator('.current-lesson-actions button').last().click()
    await page.waitForFunction(() => document.activeElement?.id === 'panel-code')
    check(label + ' practice CTA reveals and focuses code', await page.locator('#panel-code').evaluate(panel => getComputedStyle(panel).display !== 'none' && panel.getBoundingClientRect().top >= Math.max(document.querySelector('.learning-header').getBoundingClientRect().bottom, document.querySelector('.reader-view-controls').getBoundingClientRect().bottom)))
    await read()
    await page.setViewportSize({ width: width <= 1099 ? 1440 : 390, height: 1000 })
    check(label + ' resize preserves reader and workspace', await identical() && await page.locator('.document-reader').count() === 1)
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    await page.locator('.document-reader article').evaluate(article => { article.scrollTop = 120 })
    const readerTop = await page.locator('.document-reader').evaluate(reader => reader.getBoundingClientRect().top)
    await page.locator('.interface-language button').click()
    await ready()
    check(label + ' locale does not steal outer reading position', Math.abs(await page.locator('.document-reader').evaluate(reader => reader.getBoundingClientRect().top) - readerTop) < 1)
    check(label + ' locale keeps document and unit identity', page.url().endsWith('?reader=1#javascript-step-02') && await identical())
    await page.locator('.interface-language button').click()
    await ready()
    await page.locator('.document-reader').focus()
    await page.keyboard.press('Escape')
    check(label + ' Escape closes reader and restores CTA focus', await page.locator('.document-reader').count() === 0 && await page.locator('.current-lesson-actions button').first().evaluate(button => document.activeElement === button))
    check(label + ' close preserves model selection frame notes storage', await identical())
    check(label + ' editor undo history retained', await page.evaluate(() => { window.l03.editor.trigger('l03', 'undo'); return window.l03.model.getValue() === window.l03.original }))
    await page.evaluate(() => window.l03.editor.trigger('l03', 'redo'))
  }
  await page.goto(baseUrl + '/en/#javascript-step-02', { waitUntil: 'domcontentloaded' })
  await page.locator('.practice-guide footer button').first().click()
  await ready()
  await page.locator('.document-reader .document-nav button').nth(2).click()
  await ready()
  await page.locator('.document-reader .text-link').filter({ hasText: 'deployment guide' }).click()
  await ready()
  check('explicit Korean source link remains Korean in English UI', /[가-힣]/.test(await page.locator('.document-reader article h1').first().textContent()))
  await page.locator('.interface-language button').click()
  await ready()
  await page.locator('.interface-language button').click()
  await ready()
  check('locale round trip requests English missing document instead of retaining Korean source', await page.locator('.document-reader article h1').first().textContent() === 'Document not found')
  await page.locator('.learning-journey .unit-pagination button').last().click()
  await page.locator('.document-reader .dialog-header button').click()
  check('removed document trigger falls back to current lesson CTA', await page.locator('.current-lesson-actions button').first().evaluate(button => document.activeElement === button))
  await page.locator('.learning-header .header-navigation>a').click()
  await page.locator('.header-navigation>button').click()
  await page.locator('.document-dialog[open] article h1').waitFor()
  check('home usage keeps native modal contract', await page.locator('.document-dialog').evaluate(dialog => dialog.matches(':modal') && dialog.contains(document.activeElement)))
  await page.keyboard.press('Escape')
  check('home modal Escape restores usage focus', await page.locator('.header-navigation>button').evaluate(button => document.activeElement === button))
  return { checks, measurements }
}
